"""Tests for dynamic output parsers (Scenarios, Chief Synthesis, Red Team)."""
import pytest
from services.orchestrator.parsers import (
    parse_chief_synthesis,
    parse_red_team_critique,
    parse_scenarios,
)


def test_parse_scenarios_from_markdown():
    sample_text = """
1. **السيناريو الأول: الاستقرار الحذر والردع الفاعل (الاحتمالية: 60%)**
   - الوصف: استمرار توازن الردع ومنع المواجهة الشاملة عبر قنوات الوساطة [EVD-001].
   - المحركات الرئيسية: توازن الردع العسكري والتكلفة الاقتصادية الباهظة.
   - مؤشرات التحقق والرصد: انتظام الملاحة في البحر الأحمر واستقرار المعابر الحدودية.
   - الانعكاسات الاستراتيجية: إتاحة مساحة لمواصلة خطط التنمية والتحديث الدفاعي.

2. **السيناريو الثاني: تصعيد موضعي واحتكاكات محدودة (الاحتمالية: 25%)**
   - الوصف: مناوشات واستهدافات متفرقة يتم احتواؤها سريعاً [EVD-003].
   - المحركات الرئيسية: استفزازات تكتيكية ونشاط فصائل مسلحة غير منضبطة.
   - مؤشرات التحقق والرصد: ارتفاع كلفة التأمين البحري وتحركات مفاجئة.
   - الانعكاسات الاستراتيجية: ضرورة الرد الردعي الحاسم دون الانجرار إلى صراع مفتوح.

3. **السيناريو الثالث: انفراجة سياسية وتهدئة شاملة (الاحتمالية: 15%)**
   - الوصف: إبرام تفاهمات شاملة للأمن الإقليمي وتعزيز تدفقات الطاقة والتجارة.
   - المحركات الرئيسية: جهود الوساطة الدبلوماسية النشطة.
   - مؤشرات التحقق والرصد: توقيع اتفاقات أمنية واستئناف مشاريع الربط.
   - الانعكاسات الاستراتيجية: تعزيز المكانة المحورية لمصر كمركز للتجارة والتعاون.
"""
    scenarios = parse_scenarios(sample_text)
    assert len(scenarios) == 3
    assert "الاستقرار الحذر" in scenarios[0].title
    assert scenarios[0].probability_estimate == 0.60
    assert len(scenarios[0].drivers) > 0
    assert len(scenarios[0].indicators_to_watch) > 0
    assert "تصعيد موضعي" in scenarios[1].title
    assert scenarios[1].probability_estimate == 0.25


def test_parse_scenarios_from_json():
    json_text = """
هنا السيناريوهات بصيغة مهيكلة:
```json
[
  {
    "title": "سيناريو احتواء الأزمة",
    "description": "احتواء سريع للتوترات الحدودية",
    "probability_estimate": 0.7,
    "drivers": ["الوساطة الدبلوماسية"],
    "indicators_to_watch": ["فتح المعابر"],
    "strategic_implications": "استقرار خطوط التجارة"
  },
  {
    "title": "سيناريو التصعيد المحدود",
    "description": "مناوشات متقطعة على السواحل",
    "probability_estimate": 0.3,
    "drivers": ["هجمات مسيرات"],
    "indicators_to_watch": ["إغلاق موانئ"],
    "strategic_implications": "رفع الجاهزية البحرية"
  }
]
```
"""
    scenarios = parse_scenarios(json_text)
    assert len(scenarios) == 2
    assert scenarios[0].title == "سيناريو احتواء الأزمة"
    assert scenarios[0].probability_estimate == 0.7
    assert scenarios[1].title == "سيناريو التصعيد المحدود"


def test_parse_chief_synthesis():
    chief_text = """
# تقدير الموقف الاستراتيجي الشامل
## 1. الملخص التنفيذي
أظهرت القراءات الاستخباراتية المتكاملة لخلية التحليل تحولات محورية في البيئة الأمنية الإقليمية.

## 2. الأحكام الاستراتيجية الرئيسية
1. الحفاظ على التفوق والجاهزية الردعية المتكاملة على المحاور الاستراتيجية الحاكمة.
2. تأمين ممرات التجارة والطاقة في البحر الأحمر وقناة السويس وشرق المتوسط يمثل ركيزة للأمن القومي.
3. استمرار التنسيق المشترك لمنع تدفق السلاح والمجموعات غير النظامية عبر الحدود الغربية.

## 3. التداعيات على الأمن القومي والمصالح الوطنية
ترسيخ دور مصر كركيزة للاستقرار الإقليمي، وحماية حرية الملاحة الدولية في قناة السويس، وتعزيز الاستقلال العسكري بتوطين التكنولوجيا الدفاعية.

## 4. مصفوفة المخاطر والفرص
المخاطر: احتكاكات غير محسوبة على الممرات المائية وتصاعد استخدام الأنظمة المسيرة.
الفرص: قيادة مبادرات الأمن البحري الإقليمي وتوسيع التصدير الدفاعي والصناعات المشتركة.

## 5. التوصيات الاستراتيجية ذات الأولوية
1. إبقاء الجاهزية العملياتية والتعبوية لقوات تأمين الحدود والمجال البحري عند أعلى الدرجات.
2. تفعيل آليات التنسيق المباشر للإنذار المبكر مع دول الجوار والشركاء الإقليميين.
3. مواصلة برامج توطين الصناعات الدفاعية وتأمين خطوط إمداد التكنولوجيا الحيوية.
"""
    result = parse_chief_synthesis(chief_text, "سؤال استراتيجي")
    assert len(result["key_judgments"]) == 3
    assert "الحفاظ على التفوق" in result["key_judgments"][0]
    assert "ترسيخ دور مصر" in result["national_interest_implications"]
    assert "المخاطر:" in result["risks_and_opportunities"]
    assert len(result["recommendations"]) == 3
    assert "إبقاء الجاهزية العملياتية" in result["recommendations"][0]


def test_parse_red_team_critique():
    red_text = """
# مراجعة الفريق الأحمر النقدية المستقلة
## 1. نقاط القوة في التقدير
- شمولية محاور التحليل العسكري والاقتصادي والسياسي للمسرح المشترك [EVD-001].
- الارتكاز على ثوابت الأمن القومي المصري وتأمين الممرات البحرية والحدود [EVD-003].

## 2. الثغرات والادعاءات غير المثبتة
- الاعتماد على افتراض استقرار الأوضاع الداخلية لبعض الأطراف دون رصد كافٍ للضغوط التضخمية [EVD-002].
- الحاجة لمزيد من الأدلة المستقلة حول البرامج التسليحية غير المعلنة.

## 3. الافتراضات الأساسية التي تم تحديها
- افتراض أن الردع الحالي كافٍ لمنع كافة الاستفزازات البحرية دون زيادة الحضور العسكري المباشر [EVD-004].

## 4. الفرضيات والتفسيرات البديلة (ACH)
- قد تلجأ بعض الأطراف لتصعيد موضعي مفاجئ لتحسين شروط التفاوض دون نية خوض صراع شامل.

## 5. حكم الفريق الأحمر النهائي
التقرير: **مقبول مع تعديل طفيف** (accepted_with_revisions).

## 6. توصية الفريق الأحمر لصانع القرار
اعتماد التقدير مع مراعاة وضع خطط طوارئ إضافية لتأمين إمدادات الطاقة والممرات الملاحية.
"""
    critique = parse_red_team_critique(red_text)
    assert critique.verdict == "accepted_with_revisions"
    assert len(critique.strengths) == 2
    assert len(critique.weaknesses) == 2
    assert len(critique.key_assumptions_challenged) == 1
    assert len(critique.alternative_hypotheses) == 1
    assert "اعتماد التقدير" in critique.recommendations_for_chief
